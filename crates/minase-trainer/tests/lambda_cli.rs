//! 教師値を計算する各コマンドはλを必須とし、引数の解析時に範囲を検査する。
use std::process::Command;

#[test]
fn teacher_commands_require_a_finite_lambda_in_the_unit_interval() {
    let commands: &[&[&str]] = &[
        &[
            "pst",
            "train",
            "--data",
            "missing.mnsd",
            "--init",
            "missing.bin",
            "--output-dir",
            "unused",
            "--epochs",
            "1",
            "--patience",
            "1",
            "--removal-reference",
            "init",
        ],
        &[
            "fm",
            "train",
            "--data",
            "missing.mnsd",
            "--init",
            "missing.bin",
            "--output-dir",
            "unused",
            "--epochs",
            "1",
            "--patience",
            "1",
        ],
        &[
            "joint",
            "train",
            "--data",
            "missing.mnsd",
            "--base",
            "missing.bin",
            "--pst-init",
            "missing.npz",
            "--fm-init",
            "missing.npz",
            "--fm-reference",
            "missing.bin",
            "--output-dir",
            "unused",
            "--epochs",
            "1",
            "--patience",
            "1",
        ],
        &[
            "nnue",
            "train",
            "--feature-set",
            "P",
            "--width",
            "8",
            "--data",
            "missing.mnsd",
            "--init-pst",
            "missing.npz",
            "--base",
            "missing.bin",
            "--output-dir",
            "unused",
        ],
        &[
            "nnue",
            "bench-step",
            "--feature-set",
            "P",
            "--width",
            "8",
            "--batch",
            "2",
            "--steps",
            "2",
            "--data",
            "missing.mnsd",
        ],
        &[
            "nnue",
            "check-equivalence",
            "--feature-set",
            "P",
            "--width",
            "8",
            "--batch",
            "2",
            "--seed",
            "1",
        ],
        &[
            "diag",
            "pst-compare",
            "--data",
            "missing.mnsd",
            "--base",
            "missing.bin",
            "--candidate",
            "missing.bin",
            "--candidate-float",
            "missing.npz",
            "--output-dir",
            "unused",
        ],
    ];
    for arguments in commands {
        for value in [
            None,
            Some("-0.1"),
            Some("1.1"),
            Some("NaN"),
            Some("inf"),
            Some("-inf"),
        ] {
            let mut command = Command::new(env!("CARGO_BIN_EXE_minase-trainer"));
            command.args(*arguments);
            if let Some(value) = value {
                command.arg(format!("--lambda={value}"));
            }
            let output = command.output().unwrap();
            assert_eq!(
                output.status.code(),
                Some(2),
                "{arguments:?} {value:?}: {}",
                String::from_utf8_lossy(&output.stderr)
            );
            assert!(String::from_utf8_lossy(&output.stderr).contains("--lambda"));
        }
    }
}
